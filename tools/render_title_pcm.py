#!/usr/bin/env python3
"""Render the existing runtime synth on the host. Requires g++, not devkitARM.
No new soundfont/codec: extract exact synth functions from wipi_shim.cpp.
Produces one optional NitroFS cache; original MMF is never modified.
"""
from pathlib import Path
import subprocess,tempfile,struct,json,hashlib,argparse
ROOT=Path(__file__).resolve().parents[1]
def extract(marker):
 s=(ROOT/'source/wipi_shim.cpp').read_text();a=s.index(marker);b=s.index('{',a);depth=1;p=b+1
 while depth:
  if s[p]=='{':depth+=1
  elif s[p]=='}':depth-=1
  p+=1
 return s[a:p]+'\n'
def renderer_source():
 s=(ROOT/'source/wipi_shim.cpp').read_text()
 code='''#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <malloc.h>
#include <vector>
#include <fstream>
#include <iterator>
constexpr uint32_t MEDIA_SYNTH_RATE=8000,MEDIA_MAX_PCM_BYTES=6*1024*1024;
struct DummyMediaClip { int16_t *pcm=nullptr;uint32_t pcm_samples=0,sample_rate=0;uint8_t decoded_kind=0; };
static void media_release_pcm(DummyMediaClip *c){free(c->pcm);c->pcm=nullptr;}
static void DC_FlushRange(const void*,unsigned){}
'''
 for marker in ['static inline uint32_t read_be32(', 'static inline int16_t clip_s16(']:code+=extract(marker)
 a=s.index('static const uint32_t kMidiPhase11025[128]');b=s.index('};',a)+2;code+=s[a:b]+'\n'
 a=s.index('struct SmafSynthState {');b=s.index('};',a)+2;code+=s[a:b]+'\n'
 for marker in ['static int smaf_timebase_ms(', 'static bool smaf_read_vlq(', 'static bool smaf_find_mtsq(',
 'static void smaf_synth_state_init(', 'static inline int32_t synth_wave(', 'static void smaf_mix_note(', 'static int media_decode_smaf_mtr(']:code+=extract(marker)
 code+='''int main(int argc,char **argv){
 if(argc!=3)return 1;
 std::ifstream f(argv[1],std::ios::binary);std::vector<uint8_t>b((std::istreambuf_iterator<char>(f)),{});
 if(b.size()<16 || memcmp(b.data(),"MMMD",4))return 2;
 for(uint32_t p=8;p+8<=b.size();){
  uint32_t n=read_be32(b.data()+p+4);if(n>b.size()-p-8)return 3;
  if(!memcmp(b.data()+p,"MTR",3)){
   DummyMediaClip c;if(media_decode_smaf_mtr(&c,b.data()+p+8,n))return 4;
   FILE *o=fopen(argv[2],"wb");if(!o)return 5;
   bool ok=fwrite(c.pcm,2,c.pcm_samples,o)==c.pcm_samples;fclose(o);
   printf("PCM %u samples, %u Hz\\n",c.pcm_samples,c.sample_rate);free(c.pcm);return ok?0:6;
  }
  p+=8+n;
 }
 return 7;
}
'''
 return code

def fnv(b):
 h=2166136261
 for v in b:h=((h^v)*16777619)&0xffffffff
 return h

def render(output):
 with tempfile.TemporaryDirectory() as d:
  d=Path(d);(d/'render.cpp').write_text(renderer_source())
  subprocess.run(['g++','-std=c++17','-O2',str(d/'render.cpp'),'-o',str(d/'render')],check=True)
  subprocess.run([str(d/'render'),str(ROOT/'nitrofs/sound/108.mmf'),str(output)],check=True)

def main():
 ap=argparse.ArgumentParser();ap.add_argument('--verify',action='store_true');args=ap.parse_args()
 with tempfile.TemporaryDirectory() as d:
  raw=Path(d)/'title.pcm';render(raw);pcm=raw.read_bytes()
 encoded=(ROOT/'nitrofs/sound/108.mmf').read_bytes()
 header=b'ZPCM051\0'+struct.pack('<6I',len(encoded),fnv(encoded),8000,len(pcm)//2,len(pcm),fnv(pcm))
 cache=ROOT/'nitrofs/runner_audio/title108.zpc'
 manifest=ROOT/'assets/audio/title108-manifest.json'
 meta={'source':'nitrofs/sound/108.mmf','source_sha256':hashlib.sha256(encoded).hexdigest(),
       'source_size':len(encoded),'source_fnv1a':fnv(encoded),'rate':8000,'samples':len(pcm)//2,
       'pcm_sha256':hashlib.sha256(pcm).hexdigest(),'pcm_fnv1a':fnv(pcm),
       'cache':'nitrofs/runner_audio/title108.zpc','cache_sha256':hashlib.sha256(header+pcm).hexdigest(),
       'synth_source_sha256':hashlib.sha256(renderer_source().encode()).hexdigest()}
 inc=ROOT/'source/zen_title_pcm_manifest.h'
 constants='''#pragma once
// Generated by tools/render_title_pcm.py from the unchanged sound/108.mmf.
constexpr uint32_t TITLE_PCM_SOURCE_SIZE=%du;
constexpr uint32_t TITLE_PCM_SOURCE_HASH=0x%08xu;
constexpr uint32_t TITLE_PCM_SAMPLES=%du;
constexpr uint32_t TITLE_PCM_HASH=0x%08xu;
'''%(len(encoded),fnv(encoded),len(pcm)//2,fnv(pcm))
 if args.verify:
  assert cache.read_bytes()==header+pcm,'cache differs from current runtime synth'
  assert json.loads(manifest.read_text())==meta,'manifest differs'
  assert inc.read_text()==constants,'constants differ'
  print('PASS title cache bit-exact against freshly compiled runtime synth')
 else:
  cache.parent.mkdir(parents=True,exist_ok=True);cache.write_bytes(header+pcm)
  manifest.parent.mkdir(parents=True,exist_ok=True);manifest.write_text(json.dumps(meta,indent=2)+'\n')
  inc.write_text(constants);print('Generated',cache.relative_to(ROOT),len(header+pcm),'bytes')
if __name__=='__main__':main()
